function svgTipo(tipo: EstabTipo): string {
  return `<svg class="pin-mapa__ico" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${FORMAS_TIPO[tipo]}</svg>`;
}

function escapeHtml(s: string): string {
  return s.replace(
    /[&<>"']/g,
    (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c] as string,
  );
}

function formatPrecoCurto(preco: number): string {
  return preco.toLocaleString("pt-BR", {
    style: "currency",
    currency: "BRL",
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  });
}

export function pinIcon(item: ItemMapa): L.DivIcon {
  const classes = ["pin-mapa"];
  if (item.selo_azul) classes.push("pin-mapa--selo");
  if (item.preco === null) classes.push("pin-mapa--ponto");

  const texto =
    item.preco !== null
      ? `<span class="pin-mapa__texto">${escapeHtml(formatPrecoCurto(item.preco))}</span>`
      : "";

  return L.divIcon({
    className: "",
    html: `<div class="${classes.join(" ")}"><span class="pin-mapa__corpo">${svgTipo(item.estabelecimento_tipo)}${texto}</span></div>`,
    iconSize: item.preco !== null ? [76, 28] : [34, 34],
    iconAnchor: item.preco !== null ? [38, 14] : [17, 17],
  });
}
